"""Справочники, которые не заводят отдельных сущностей.

Жанры — ответ анкеты и подсказка в карточке книги, а не объект со связями:
списком в коде их проще держать в согласии с тем, что приходит из внешних
источников, чем таблицей, которую придётся синхронизировать.
"""

GENRES: tuple[str, ...] = (
    "Классика",
    "Современная проза",
    "Фантастика",
    "Фэнтези",
    "Детектив",
    "Триллер",
    "Хоррор",
    "Поэзия",
    "Драматургия",
    "Нон-фикшн",
    "История",
    "Философия",
    "Психология",
    "Наука",
    "Биографии",
    "Публицистика",
    "Young adult",
    "Комиксы и графические романы",
)

GENRE_SET = frozenset(GENRES)


def clean_genres(values: list[str] | None) -> list[str]:
    """Оставляет только известные жанры, сохраняя порядок справочника.

    Список приходит из клиента, а значит может содержать что угодно; молча
    отбрасываем лишнее вместо ошибки — анкета не должна падать из-за того,
    что справочник обновился, а вкладка у человека открыта со вчера.
    """
    if not values:
        return []
    chosen = set(values)
    return [genre for genre in GENRES if genre in chosen]


# Направления ЦУ. Порядок и подписи живут здесь, а не в интерфейсе: анкету
# рисует и клиент, и оргкомитет читает те же названия в аналитике.
PROGRAM_TITLES: dict[str, str] = {
    "development": "Разработка",
    "ai": "Искусственный интеллект",
    "business": "Бизнес и аналитика",
    "design": "Дизайн",
    "undecided": "Ещё не определился",
}

# Этот вариант показываем только первокурсникам: со второго курса направление
# уже выбрано, и «не определился» изображал бы неопределённость там, где её нет.
FIRST_YEAR_ONLY = frozenset({"undecided"})


def program_title(key: str | None) -> str | None:
    return PROGRAM_TITLES.get(key) if key else None
