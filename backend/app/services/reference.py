"""Справочники, которые не заводят отдельных сущностей.

Жанры — ответ анкеты и подсказка в карточке книги, а не объект со связями:
списком в коде их проще держать в согласии с тем, что приходит из внешних
источников, чем таблицей, которую придётся синхронизировать.
"""

GENRES: tuple[str, ...] = (
    "Классика",
    "Современная проза",
    "Фантастика",
    "Фэнтези",
    "Детектив",
    "Триллер",
    "Хоррор",
    "Поэзия",
    "Драматургия",
    "Нон-фикшн",
    "История",
    "Философия",
    "Психология",
    "Наука",
    "Биографии",
    "Публицистика",
    "Young adult",
    "Комиксы и графические романы",
)

GENRE_SET = frozenset(GENRES)


def clean_genres(values: list[str] | None) -> list[str]:
    """Оставляет только известные жанры, сохраняя порядок справочника.

    Список приходит из клиента, а значит может содержать что угодно; молча
    отбрасываем лишнее вместо ошибки — анкета не должна падать из-за того,
    что справочник обновился, а вкладка у человека открыта со вчера.
    """
    if not values:
        return []
    chosen = set(values)
    return [genre for genre in GENRES if genre in chosen]
